#!/usr/bin/env node
/**
 * Pin each Python service's dependencies in <service>/requirements.txt:
 *
 *   npm run lock
 *
 * Dependencies are resolved inside the service's own Docker base image (its Dockerfile's FROM line),
 * so the pins match what the container actually installs. The Dockerfiles install from
 * requirements.txt, and `npm run setup` uses it as constraints. Run this after changing
 * dependencies in a pyproject.toml, then commit the result. Needs Docker running.
 */
import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { PYTHON_PROJECTS, ROOT, fail } from "./lib.mjs";

const RESOLVE = [
  "set -e",
  "cat > pyproject.toml",
  `python -c "import tomllib; print('\\n'.join(tomllib.load(open('pyproject.toml', 'rb'))['project']['dependencies']))" > requirements.in`,
  "pip install --quiet --no-cache-dir --disable-pip-version-check --root-user-action=ignore -r requirements.in >&2",
  "pip freeze --disable-pip-version-check",
].join("\n");

if (spawnSync("docker", ["info"], { stdio: "ignore" }).status !== 0) fail("Docker is not running.");

for (const project of PYTHON_PROJECTS) {
  const dir = join(ROOT, project);
  const image = readFileSync(join(dir, "Dockerfile"), "utf8").match(/^FROM\s+(\S+)/m)?.[1];
  if (!image) fail(`${project}/Dockerfile has no FROM line.`);

  console.log(`→ ${project}: resolving dependencies in ${image}`);
  const result = spawnSync("docker", ["run", "--rm", "-i", "-w", "/lock", image, "sh", "-c", RESOLVE], {
    input: readFileSync(join(dir, "pyproject.toml")),
    encoding: "utf8",
    stdio: ["pipe", "pipe", "inherit"],
  });
  if (result.status !== 0) fail(`Resolving ${project} dependencies failed.`);

  const pins = result.stdout.split(/\r?\n/).filter((line) => line.includes("=="));
  const header = [
    `# Pinned dependencies for ${project}, resolved in ${image}. Generated by \`npm run lock\`; don't edit.`,
    "# Edit dependencies in pyproject.toml, then re-run `npm run lock`.",
  ];
  writeFileSync(join(dir, "requirements.txt"), [...header, ...pins].join("\n") + "\n");
  console.log(`  wrote ${project}/requirements.txt (${pins.length} packages)`);
}
